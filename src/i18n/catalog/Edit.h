// Two conventions this catalog follows because they are expensive to
// retrofit. A count is LABELLED rather than inflected ("Selected: 3", never
// "3 selected"), so no language needs a plural rule for it. And a keyboard
// shortcut is not interface copy: B is B in every language, exactly as
// --sh-degree is, so the keys inside a hint sentence stay Latin.

