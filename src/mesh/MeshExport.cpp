MeshFormatSpec parse_one_mesh_format(const std::string& token) {
    std::string s = token;
    std::transform(s.begin(), s.end(), s.begin(),
                   [](unsigned char c) { return (char)std::tolower(c); });
    if (!s.empty() && s[0] == '.') s.erase(s.begin());

    MeshFormatSpec spec;
    std::string enc;
    size_t plus = s.find('+');
    if (plus != std::string::npos) {
        enc = s.substr(plus + 1);
        s.resize(plus);
    }
    if (s != "ply" && s != "obj" && s != "gltf" && s != "glb" && s != "stl")
        fail("unknown mesh format '" + token + "' (expected ply, obj, gltf, "
             "glb or stl, optionally with +png / +jpg / +jpeg<quality>)");
    spec.fmt = s;
    if (enc.empty()) return spec;                       // default: PNG

    // split the encoding into name + optional quality digits
    size_t d = enc.find_first_of("0123456789");
    std::string ename = enc.substr(0, d);
    std::string digits = d == std::string::npos ? "" : enc.substr(d);
    if (ename == "png") {
        if (!digits.empty())
            fail("'" + token + "': png takes no quality value");
    } else if (ename == "jpg" || ename == "jpeg") {
        spec.jpeg = true;
        if (!digits.empty()) {
            try { spec.quality = std::stoi(digits); } catch (...) { spec.quality = 0; }
            if (spec.quality < 1 || spec.quality > 100)
                fail("'" + token + "': JPEG quality must be in 1..100");
        }
    } else {
        fail("'" + token + "': unknown texture encoding '+" + enc +
             "' (expected +png, +jpg, or +jpeg<quality>)");
    }
    return spec;
}

std::vector<MeshFormatSpec> parse_mesh_formats(const std::string& csv) {
    std::vector<MeshFormatSpec> out;
    size_t pos = 0;
    while (pos <= csv.size()) {
        size_t comma = csv.find(',', pos);
        std::string tok = csv.substr(
            pos, comma == std::string::npos ? std::string::npos : comma - pos);
        // trim
        while (!tok.empty() && std::isspace((unsigned char)tok.front())) tok.erase(tok.begin());
        while (!tok.empty() && std::isspace((unsigned char)tok.back())) tok.pop_back();
        if (!tok.empty()) {
            MeshFormatSpec spec = parse_one_mesh_format(tok);
            for (const auto& o : out)
                if (o.fmt == spec.fmt)
                    fail("format '" + spec.fmt + "' requested more than once "
                         "(the outputs would overwrite each other)");
            out.push_back(std::move(spec));
        }
        if (comma == std::string::npos) break;
        pos = comma + 1;
    }
    return out;
}

std::string check_export_support(const MeshFormatSpec& spec, MeshColorMode mode) {
    if (spec.fmt == "ply" && mode == MeshColorMode::Texture)
        return "PLY does not support textured meshes; use vertex color "
               "(or export OBJ/GLTF/GLB)";
    if (spec.fmt == "obj" && mode == MeshColorMode::Vertex)
        return "OBJ has no standard per-vertex color; use a texture "
               "(or export PLY/GLTF/GLB)";
    if (spec.fmt == "stl" && mode != MeshColorMode::None)
        return "STL carries no color at all; use no color "
               "(or export PLY/OBJ/GLTF/GLB)";
    if (spec.jpeg && mode != MeshColorMode::Texture)
        return "'" + spec.token() + "': a texture encoding was given but the "
               "color mode is not 'texture'";
    return "";
}

const char* mesh_color_token(MeshColorMode mode) {
    switch (mode) {
        case MeshColorMode::None:    return "none";
        case MeshColorMode::Texture: return "texture";
        default:                     return "vertex";
    }
}

bool parse_mesh_color(const std::string& token, MeshColorMode& out) {
    std::string s = token;
    std::transform(s.begin(), s.end(), s.begin(),
                   [](unsigned char c) { return (char)std::tolower(c); });
    for (int i = 0; i < kNumMeshColorModes; ++i)
        if (s == mesh_color_token((MeshColorMode)i)) {
            out = (MeshColorMode)i;
            return true;
        }
    return false;
}

std::vector<MeshColorMode> parse_mesh_colors(const std::string& csv) {
    std::vector<MeshColorMode> out;
    size_t pos = 0;
    while (pos <= csv.size()) {
        const size_t comma = csv.find(',', pos);
        std::string tok = csv.substr(
            pos, comma == std::string::npos ? std::string::npos : comma - pos);
        while (!tok.empty() && std::isspace((unsigned char)tok.front())) tok.erase(tok.begin());
        while (!tok.empty() && std::isspace((unsigned char)tok.back())) tok.pop_back();
        if (!tok.empty()) {
            MeshColorMode m;
            if (!parse_mesh_color(tok, m))
                fail("unknown color mode '" + tok +
                     "' (expected none, vertex or texture)");
            for (MeshColorMode o : out)
                if (o == m)
                    fail("color mode '" + tok + "' requested more than once");
            out.push_back(m);
        }
        if (comma == std::string::npos) break;
        pos = comma + 1;
    }
    return out;
}

std::string mesh_output_strip_ext(const std::string& path) {
    for (const char* ext : {".ply", ".obj", ".gltf", ".glb", ".stl"}) {
        const size_t n = std::strlen(ext);
        if (path.size() > n && path.compare(path.size() - n, n, ext) == 0)
            return path.substr(0, path.size() - n);
    }
    return path;
}

std::string mesh_output_base(const std::string& base_path, MeshColorMode mode,
                             int num_modes) {
    if (num_modes <= 1) return base_path;
    switch (mode) {
        case MeshColorMode::None:    return base_path + "_nocolor";
        case MeshColorMode::Texture: return base_path + "_textured";
        default:                     return base_path + "_vertexcolor";
    }
}

std::vector<MeshOutputRequest> plan_mesh_outputs(
    const std::vector<MeshFormatSpec>& specs,
    const std::vector<MeshColorMode>& modes, const std::string& base_path,
    std::vector<std::string>* dropped) {
    // Which modes survive is what decides whether the names need a suffix, so
    // the pairs are collected first and the paths only afterwards.
    std::vector<MeshOutputRequest> out;
    std::vector<MeshColorMode> kept;
    for (MeshColorMode mode : modes) {
        bool any = false;
        for (const MeshFormatSpec& spec : specs) {
            const std::string err = check_export_support(spec, mode);
            if (!err.empty()) {
                if (dropped)
                    dropped->push_back(spec.token() + " + " +
                                       mesh_color_token(mode) + ": " + err);
                continue;
            }
            MeshOutputRequest r;
            r.spec = spec;
            r.mode = mode;
            out.push_back(std::move(r));
            any = true;
        }
        if (any) kept.push_back(mode);
    }
    for (MeshOutputRequest& r : out)
        r.base = mesh_output_base(base_path, r.mode, (int)kept.size());
    return out;
}

std::vector<std::string> mesh_output_paths(const MeshFormatSpec& spec,
                                           MeshColorMode mode,
                                           const std::string& base_path) {
    const bool tex = mode == MeshColorMode::Texture;
    std::vector<std::string> out;
    out.push_back(base_path + "." + spec.fmt);
    if (spec.fmt == "obj" && tex) {
        out.push_back(base_path + ".mtl");
        out.push_back(base_path + "." + spec.tex_ext());
    } else if (spec.fmt == "gltf") {
        out.push_back(base_path + ".bin");
        if (tex) out.push_back(base_path + "." + spec.tex_ext());
    }
    return out;
}

std::string check_mesh_outputs_safe(const std::vector<MeshOutputRequest>& outputs,
                                    const std::vector<std::string>& inputs) {
    std::error_code ec;
    auto same = [&](const std::string& a, const std::string& b) {
        if (a == b) return true;
        if (!std::filesystem::exists(a, ec) ||
            !std::filesystem::exists(b, ec))
            return std::filesystem::weakly_canonical(a, ec) ==
                   std::filesystem::weakly_canonical(b, ec);
        return std::filesystem::equivalent(a, b, ec) && !ec;
    };
    for (const MeshOutputRequest& req : outputs)
        for (const std::string& o : mesh_output_paths(req.spec, req.mode, req.base))
            for (const std::string& in : inputs) {
                if (in.empty()) continue;
                if (same(o, in))
                    return "refusing to write " + o +
                           ": that is this run's own input. Pass a different "
                           "--output.";
            }
    return "";
}

void write_mesh(const MeshData& mesh, MeshColorMode mode,
                const MeshFormatSpec& spec, const std::string& base_path,
                bool verbose) {
    std::string err = check_export_support(spec, mode);
    if (!err.empty()) fail(err);
    check_mesh(mesh, mode);
    ensure_parent_dirs(base_path);

    const std::string& fmt = spec.fmt;
    if (fmt == "ply")       write_ply_file(mesh, mode, base_path);
    else if (fmt == "obj")  write_obj_file(mesh, mode, spec, base_path);
    else if (fmt == "stl")  write_stl_file(mesh, base_path);
    else if (fmt == "gltf") write_gltf_file(mesh, mode, spec, base_path, false);
    else                    write_gltf_file(mesh, mode, spec, base_path, true);

    if (verbose) {
        std::string extra;
        if (fmt == "obj" && mode == MeshColorMode::Texture)
            extra = std::string(" (+ .mtl, .") + spec.tex_ext() + ")";
        else if (fmt == "gltf")
            extra = mode == MeshColorMode::Texture
                ? std::string(" (+ .bin, .") + spec.tex_ext() + ")"
                : std::string(" (+ .bin)");
        mlog::out(mlog::Stage::Wrote, mmsg::wrote_file,
                  {base_path + "." + fmt + extra, (long long)mesh.V.size(),
                   (long long)mesh.F.size()});
    }
}

void compute_vertex_normals(MeshData& mesh) {
    const size_t nv = mesh.V.size();
    mesh.N.assign(nv, {0.f, 0.f, 0.f});
    for (const auto& t : mesh.F) {
        const auto& a = mesh.V[t[0]];
        const auto& b = mesh.V[t[1]];
        const auto& c = mesh.V[t[2]];
        float e1[3] = {b[0]-a[0], b[1]-a[1], b[2]-a[2]};
        float e2[3] = {c[0]-a[0], c[1]-a[1], c[2]-a[2]};
        // cross product = 2*area-weighted face normal
        float n[3] = {e1[1]*e2[2] - e1[2]*e2[1],
                      e1[2]*e2[0] - e1[0]*e2[2],
                      e1[0]*e2[1] - e1[1]*e2[0]};
        for (int k = 0; k < 3; ++k) {
            mesh.N[t[k]][0] += n[0];
            mesh.N[t[k]][1] += n[1];
            mesh.N[t[k]][2] += n[2];
        }
    }
    for (auto& n : mesh.N) {
        float l = std::sqrt(n[0]*n[0] + n[1]*n[1] + n[2]*n[2]);
        if (l > 1e-20f) { n[0] /= l; n[1] /= l; n[2] /= l; }
        else            { n[0] = 0.f; n[1] = 0.f; n[2] = 1.f; }
    }
}

void print_mesh_stats(const MeshData& mesh) {
    const size_t nv = mesh.V.size(), nf = mesh.F.size();
    if (nf == 0) {
        mlog::out(mlog::Stage::Stats, mmsg::stats_empty);
        return;
    }

    // undirected edge -> (face count, winding balance). For a consistently
    // oriented 2-face edge the two traversals are opposite: balance == 0.
    std::unordered_map<int64_t, std::pair<int,int>> edges;
    edges.reserve(nf * 3);
    const int64_t P = (int64_t)nv;
    for (const auto& f : mesh.F)
        for (int k = 0; k < 3; ++k) {
            int a = f[k], b = f[(k+1)%3];
            int64_t lo = a < b ? a : b, hi = a < b ? b : a;
            auto& e = edges[lo * P + hi];
            e.first += 1;
            e.second += (a < b) ? 1 : -1;
        }
    long n_bnd = 0, n_nonmanif = 0, n_misoriented = 0;
    for (const auto& kv : edges) {
        if (kv.second.first == 1) ++n_bnd;
        else if (kv.second.first > 2) ++n_nonmanif;
        else if (kv.second.second != 0) ++n_misoriented;
    }

    // duplicate faces
    std::unordered_set<int64_t> seen;
    seen.reserve(nf * 2);
    long n_dup = 0;
    for (const auto& f : mesh.F) {
        int a = f[0], b = f[1], c = f[2];
        if (a > b) std::swap(a, b);
        if (b > c) std::swap(b, c);
        if (a > b) std::swap(a, b);
        if (!seen.insert((int64_t)a * P * P + (int64_t)b * P + c).second) ++n_dup;
    }

    // connected components (union-find over vertices)
    std::vector<int> parent(nv);
    for (size_t i = 0; i < nv; ++i) parent[i] = (int)i;
    std::function<int(int)> find = [&](int x) {
        while (parent[x] != x) { parent[x] = parent[parent[x]]; x = parent[x]; }
        return x;
    };
    for (const auto& f : mesh.F) {
        int a = find(f[0]), b = find(f[1]), c = find(f[2]);
        if (a != b) parent[a] = b;
        b = find(b);
        if (b != c) parent[b] = c;
    }
    std::unordered_set<int> roots;
    for (const auto& f : mesh.F) roots.insert(find(f[0]));

    // triangle min-angle stats
    long n_deg5 = 0, n_deg15 = 0;
    double min_angle = 180.0;
    for (const auto& f : mesh.F) {
        const auto& A = mesh.V[f[0]];
        const auto& B = mesh.V[f[1]];
        const auto& C2 = mesh.V[f[2]];
        auto d2 = [](const std::array<float,3>& p, const std::array<float,3>& q) {
            double dx = p[0]-q[0], dy = p[1]-q[1], dz = p[2]-q[2];
            return dx*dx + dy*dy + dz*dz;
        };
        double la = d2(B, C2), lb = d2(C2, A), lc = d2(A, B);
        auto ang = [](double opp, double s1, double s2) {
            double dn = 2.0 * std::sqrt(s1 * s2);
            double c = dn > 1e-300 ? (s1 + s2 - opp) / dn : 1.0;
            return std::acos(std::min(std::max(c, -1.0), 1.0)) * 57.29577951308232;
        };
        double m = std::min(ang(la, lb, lc), std::min(ang(lb, lc, la), ang(lc, la, lb)));
        min_angle = std::min(min_angle, m);
        if (m < 5.0) ++n_deg5;
        if (m < 15.0) ++n_deg15;
    }

    mlog::out(mlog::Stage::Stats, mmsg::stats_line,
              {(long long)nv, (long long)nf, (long long)roots.size(), n_bnd,
               n_nonmanif, n_misoriented, n_dup, mlog::num(min_angle, 2),
               n_deg5, n_deg15});
}

