[[noreturn]] void fail(const std::string& msg) { throw std::runtime_error("mesh export: " + msg); }

std::string basename_of(const std::string& path) {
    size_t p = path.find_last_of("/\\");
    return p == std::string::npos ? path : path.substr(p + 1);
}

// Create every missing directory prefix of `path` (a file path). Failures are
// ignored here; the subsequent fopen reports real problems with context.
void ensure_parent_dirs(const std::string& path) {
    for (size_t i = 1; i < path.size(); ++i) {
        if (path[i] != '/' && path[i] != '\\') continue;
        std::string dir = path.substr(0, i);
#ifdef _WIN32
        _mkdir(dir.c_str());
#else
        mkdir(dir.c_str(), 0755);
#endif
    }
}

spirula::BufferedOutputFile open_binary(const std::string& path) {
    spirula::BufferedOutputFile f(path, std::ios::binary);
    if (!f) fail("cannot open " + path + " for writing");
    return f;
}

// sRGB (display, [0,1]) -> linear. glTF COLOR_0 is a linear multiplier, so
// the baked display-referred colors are linearized on export.
inline float srgb_to_linear(float c) {
    return c <= 0.04045f ? c / 12.92f : std::pow((c + 0.055f) / 1.055f, 2.4f);
}

void write_tex_file(const MeshData& mesh, const MeshFormatSpec& spec,
                    const std::string& path) {
    int ok = spec.jpeg
        ? stbi_write_jpg(path.c_str(), mesh.tex_width, mesh.tex_height, 3,
                         mesh.texture.data(), spec.quality)
        : stbi_write_png(path.c_str(), mesh.tex_width, mesh.tex_height, 3,
                         mesh.texture.data(), mesh.tex_width * 3);
    if (!ok) fail("failed to write " + path);
}

std::vector<unsigned char> encode_tex_mem(const MeshData& mesh,
                                          const MeshFormatSpec& spec) {
    std::vector<unsigned char> out;
    out.reserve((size_t)mesh.tex_width * mesh.tex_height);  // rough
    auto sink = [](void* ctx, void* data, int size) {
        auto* v = static_cast<std::vector<unsigned char>*>(ctx);
        v->insert(v->end(), (unsigned char*)data, (unsigned char*)data + size);
    };
    int ok = spec.jpeg
        ? stbi_write_jpg_to_func(sink, &out, mesh.tex_width, mesh.tex_height, 3,
                                 mesh.texture.data(), spec.quality)
        : stbi_write_png_to_func(sink, &out, mesh.tex_width, mesh.tex_height, 3,
                                 mesh.texture.data(), mesh.tex_width * 3);
    if (!ok) fail(std::string("failed to encode texture ") + spec.tex_ext());
    return out;
}

void check_mesh(const MeshData& mesh, MeshColorMode mode) {
    if (mode == MeshColorMode::Vertex && mesh.C.size() != mesh.V.size())
        fail("vertex-color mode but mesh has no per-vertex colors");
    if (mode == MeshColorMode::Texture) {
        if (mesh.UV.size() != mesh.V.size())
            fail("texture mode but mesh has no per-vertex UVs");
        if (mesh.tex_width <= 0 || mesh.tex_height <= 0 ||
            mesh.texture.size() != (size_t)mesh.tex_width * mesh.tex_height * 3)
            fail("texture mode but the baked texture is missing/mis-sized");
    }
}

// ---------------------------------------------------------------------------
// PLY (binary little-endian)
// ---------------------------------------------------------------------------

void write_ply_file(const MeshData& mesh, MeshColorMode mode,
                    const std::string& base) {
    const bool has_n = mesh.N.size() == mesh.V.size();
    const bool has_c = mode == MeshColorMode::Vertex;
    auto f = open_binary(base + ".ply");
    f << "ply\nformat binary_little_endian 1.0\n";
    f << "comment generated by Spirula Studio meshing\n";
    f << "element vertex " << mesh.V.size() << "\n";
    f << "property float x\nproperty float y\nproperty float z\n";
    if (has_n)
        f << "property float nx\nproperty float ny\nproperty float nz\n";
    if (has_c)
        f << "property uchar red\nproperty uchar green\nproperty uchar blue\n";
    f << "element face " << mesh.F.size() << "\n";
    f << "property list uchar int vertex_indices\n";
    f << "end_header\n";

    // row-buffered writes (a row is at most 6 floats + 3 bytes)
    std::vector<char> buf;
    buf.reserve(1 << 20);
    auto put = [&](const void* p, size_t n) {
        const char* c = (const char*)p;
        buf.insert(buf.end(), c, c + n);
        if (buf.size() > (1 << 20) - 64) { f.write(buf.data(), buf.size()); buf.clear(); }
    };
    for (size_t i = 0; i < mesh.V.size(); ++i) {
        put(mesh.V[i].data(), 12);
        if (has_n) put(mesh.N[i].data(), 12);
        if (has_c) put(mesh.C[i].data(), 3);
    }
    for (const auto& t : mesh.F) {
        unsigned char n3 = 3;
        put(&n3, 1);
        int idx[3] = {t[0], t[1], t[2]};
        put(idx, sizeof idx);
    }
    f.write(buf.data(), buf.size());
    f.flush();
    if (!f) fail("write failed for " + base + ".ply");
}

// ---------------------------------------------------------------------------
// STL (binary)
//
// Geometry only, and every triangle carries its own three vertices: that is
// the whole format. The facet normal is the one the file stores.
// ---------------------------------------------------------------------------

void write_stl_file(const MeshData& mesh, const std::string& base) {
    auto f = open_binary(base + ".stl");
    char header[80] = {};
    std::snprintf(header, sizeof header, "Spirula Studio meshing");
    f.write(header, 80);
    const uint32_t n = (uint32_t)mesh.F.size();
    f.write((const char*)&n, 4);

    std::vector<char> buf;
    buf.reserve(1 << 20);
    auto put = [&](const void* p, size_t n2) {
        const char* c = (const char*)p;
        buf.insert(buf.end(), c, c + n2);
        if (buf.size() > (1 << 20) - 64) { f.write(buf.data(), buf.size()); buf.clear(); }
    };
    for (const auto& t : mesh.F) {
        const auto &A = mesh.V[t[0]], &B = mesh.V[t[1]], &C = mesh.V[t[2]];
        float e1[3] = {B[0] - A[0], B[1] - A[1], B[2] - A[2]};
        float e2[3] = {C[0] - A[0], C[1] - A[1], C[2] - A[2]};
        float nx[3] = {e1[1] * e2[2] - e1[2] * e2[1],
                       e1[2] * e2[0] - e1[0] * e2[2],
                       e1[0] * e2[1] - e1[1] * e2[0]};
        const float len = std::sqrt(nx[0]*nx[0] + nx[1]*nx[1] + nx[2]*nx[2]);
        if (len > 0.0f) for (float& v : nx) v /= len;
        put(nx, 12);
        put(A.data(), 12);
        put(B.data(), 12);
        put(C.data(), 12);
        const uint16_t attr = 0;
        put(&attr, 2);
    }
    f.write(buf.data(), buf.size());
    f.flush();
    if (!f) fail("write failed for " + base + ".stl");
}

// ---------------------------------------------------------------------------
// OBJ (+ MTL + PNG when textured)
// ---------------------------------------------------------------------------

void write_obj_file(const MeshData& mesh, MeshColorMode mode,
                    const MeshFormatSpec& spec, const std::string& base) {
    const bool has_uv = mode == MeshColorMode::Texture;
    const bool has_n = mesh.N.size() == mesh.V.size();
    const std::string name = basename_of(base);

    FILE* f = std::fopen((base + ".obj").c_str(), "w");
    if (!f) fail("cannot open " + base + ".obj for writing");
    std::unique_ptr<char[]> iobuf(new char[spirula::kFileBufferBytes]);
    setvbuf(f, iobuf.get(), _IOFBF, spirula::kFileBufferBytes);

    std::fprintf(f, "# generated by Spirula Studio meshing\n");
    if (has_uv) std::fprintf(f, "mtllib %s.mtl\n", name.c_str());
    std::fprintf(f, "o %s\n", name.c_str());
    for (const auto& v : mesh.V)
        std::fprintf(f, "v %.7g %.7g %.7g\n", v[0], v[1], v[2]);
    if (has_uv)
        for (const auto& uv : mesh.UV)     // OBJ v runs bottom-up
            std::fprintf(f, "vt %.7g %.7g\n", uv[0], 1.0f - uv[1]);
    if (has_n)
        for (const auto& n : mesh.N)
            std::fprintf(f, "vn %.5g %.5g %.5g\n", n[0], n[1], n[2]);
    if (has_uv) std::fprintf(f, "usemtl %s\n", name.c_str());
    for (const auto& t : mesh.F) {
        int a = t[0] + 1, b = t[1] + 1, c = t[2] + 1;
        if (has_uv && has_n)
            std::fprintf(f, "f %d/%d/%d %d/%d/%d %d/%d/%d\n", a,a,a, b,b,b, c,c,c);
        else if (has_uv)
            std::fprintf(f, "f %d/%d %d/%d %d/%d\n", a,a, b,b, c,c);
        else if (has_n)
            std::fprintf(f, "f %d//%d %d//%d %d//%d\n", a,a, b,b, c,c);
        else
            std::fprintf(f, "f %d %d %d\n", a, b, c);
    }
    bool ok = !std::ferror(f);
    ok = std::fclose(f) == 0 && ok;
    if (!ok) fail("write failed for " + base + ".obj");

    if (has_uv) {
        FILE* m = std::fopen((base + ".mtl").c_str(), "w");
        if (!m) fail("cannot open " + base + ".mtl for writing");
        std::fprintf(m,
            "newmtl %s\nKa 1 1 1\nKd 1 1 1\nKs 0 0 0\nd 1\nillum 1\nmap_Kd %s.%s\n",
            name.c_str(), name.c_str(), spec.tex_ext());
        std::fclose(m);
        write_tex_file(mesh, spec, base + "." + spec.tex_ext());
    }
}

// ---------------------------------------------------------------------------
// glTF 2.0 (.gltf JSON + .bin [+ .png], or single-file .glb)
// ---------------------------------------------------------------------------

inline void pad_to_4(std::vector<unsigned char>& v, unsigned char fill) {
    while (v.size() % 4) v.push_back(fill);
}

void append_bytes(std::vector<unsigned char>& v, const void* p, size_t n) {
    const unsigned char* c = (const unsigned char*)p;
    v.insert(v.end(), c, c + n);
}

void write_gltf_file(const MeshData& mesh, MeshColorMode mode,
                     const MeshFormatSpec& spec, const std::string& base,
                     bool glb) {
    const bool has_uv = mode == MeshColorMode::Texture;
    const bool has_c = mode == MeshColorMode::Vertex;
    const bool has_n = mesh.N.size() == mesh.V.size();
    const size_t nv = mesh.V.size(), nf = mesh.F.size();
    const std::string name = basename_of(base);
    // 16-bit indices whenever they fit -- larger viewer compatibility (some
    // WebGL1-era viewers need an extension for 32-bit element indices), and
    // it matches the convention of the Khronos sample models.
    const bool idx16 = nv <= 65535;

    // ---- binary buffer ----
    std::vector<unsigned char> bin;
    bin.reserve(nf * (idx16 ? 6 : 12) +
                nv * (12 + (has_n ? 12 : 0) + (has_c ? 12 : 0) +
                      (has_uv ? 8 : 0)) + 64);
    struct View { size_t off, len; int target; };  // target 0 = none
    std::vector<View> views;
    auto add_view = [&](const void* p, size_t n, int target) -> int {
        pad_to_4(bin, 0);
        views.push_back({bin.size(), n, target});
        append_bytes(bin, p, n);
        return (int)views.size() - 1;
    };

    int view_idx;
    if (idx16) {
        std::vector<uint16_t> idx(nf * 3);
        for (size_t t = 0; t < nf; ++t)
            for (int k = 0; k < 3; ++k) idx[3*t + k] = (uint16_t)mesh.F[t][k];
        view_idx = add_view(idx.data(), idx.size() * 2, 34963);
    } else {
        std::vector<uint32_t> idx(nf * 3);
        for (size_t t = 0; t < nf; ++t)
            for (int k = 0; k < 3; ++k) idx[3*t + k] = (uint32_t)mesh.F[t][k];
        view_idx = add_view(idx.data(), idx.size() * 4, 34963);
    }
    int view_pos = add_view(mesh.V.data(), nv * 12, 34962);
    int view_nrm = -1, view_col = -1, view_uv = -1, view_img = -1;
    if (has_n) view_nrm = add_view(mesh.N.data(), nv * 12, 34962);
    if (has_c) {
        // COLOR_0 as float VEC3 of the LINEARIZED color (glTF colors are
        // linear) -- the most widely supported layout (what the Khronos
        // vertex-color sample uses).
        std::vector<float> col(nv * 3);
        for (size_t i = 0; i < nv; ++i)
            for (int k = 0; k < 3; ++k)
                col[3*i + k] = srgb_to_linear(mesh.C[i][k] / 255.0f);
        view_col = add_view(col.data(), col.size() * 4, 34962);
    }
    if (has_uv) view_uv = add_view(mesh.UV.data(), nv * 8, 34962);

    std::vector<unsigned char> img;
    if (has_uv && glb) {
        img = encode_tex_mem(mesh, spec);
        view_img = add_view(img.data(), img.size(), 0);
    }
    pad_to_4(bin, 0);

    // ---- POSITION min/max (required by the spec) ----
    float mn[3] = {1e30f, 1e30f, 1e30f}, mx[3] = {-1e30f, -1e30f, -1e30f};
    for (const auto& v : mesh.V)
        for (int k = 0; k < 3; ++k) {
            mn[k] = std::min(mn[k], v[k]);
            mx[k] = std::max(mx[k], v[k]);
        }
    if (nv == 0) { for (int k = 0; k < 3; ++k) mn[k] = mx[k] = 0.0f; }

    // ---- JSON ----
    std::string j;
    j.reserve(4096);
    char tmp[1024];
    auto add = [&](const char* fmt, ...) {
        va_list ap;
        va_start(ap, fmt);
        std::vsnprintf(tmp, sizeof tmp, fmt, ap);
        va_end(ap);
        j += tmp;
    };
    // NOTE: no KHR_materials_unlit. Viewers with partial support for the
    // extension were observed rendering the material as plain white; a rough
    // non-metal PBR material displays baked colors acceptably everywhere.
    j += "{\"asset\":{\"version\":\"2.0\",\"generator\":\"Spirula Studio meshing\"},";
    j += "\"scene\":0,\"scenes\":[{\"nodes\":[0]}],";
    add("\"nodes\":[{\"mesh\":0,\"name\":\"%s\"}],", name.c_str());

    // mesh + primitive
    j += "\"meshes\":[{\"primitives\":[{\"attributes\":{";
    int acc = 0;
    int acc_idx = acc++;
    int acc_pos = acc++;
    add("\"POSITION\":%d", acc_pos);
    int acc_nrm = -1, acc_col = -1, acc_uv = -1;
    if (has_n)  { acc_nrm = acc++; add(",\"NORMAL\":%d", acc_nrm); }
    if (has_c)  { acc_col = acc++; add(",\"COLOR_0\":%d", acc_col); }
    if (has_uv) { acc_uv = acc++; add(",\"TEXCOORD_0\":%d", acc_uv); }
    add("},\"indices\":%d,\"material\":0,\"mode\":4}]}],", acc_idx);

    // material
    j += "\"materials\":[{";
    if (has_uv)
        j += "\"pbrMetallicRoughness\":{\"baseColorTexture\":{\"index\":0},"
             "\"metallicFactor\":0,\"roughnessFactor\":1},";
    else
        j += "\"pbrMetallicRoughness\":{\"baseColorFactor\":[1,1,1,1],"
             "\"metallicFactor\":0,\"roughnessFactor\":1},";
    j += "\"doubleSided\":true}],";

    // texture / image / sampler
    if (has_uv) {
        const char* mime = spec.jpeg ? "image/jpeg" : "image/png";
        j += "\"samplers\":[{\"magFilter\":9729,\"minFilter\":9987,"
             "\"wrapS\":33071,\"wrapT\":33071}],";
        j += "\"textures\":[{\"sampler\":0,\"source\":0}],";
        if (glb)
            add("\"images\":[{\"bufferView\":%d,\"mimeType\":\"%s\"}],",
                view_img, mime);
        else
            add("\"images\":[{\"uri\":\"%s.%s\"}],", name.c_str(), spec.tex_ext());
    }

    // accessors
    j += "\"accessors\":[";
    add("{\"bufferView\":%d,\"componentType\":%d,\"count\":%zu,\"type\":\"SCALAR\"}",
        view_idx, idx16 ? 5123 : 5125, nf * 3);
    // %.17g: the validator parses JSON min/max as doubles and compares them
    // against the (float) accessor data widened to double -- 17 significant
    // digits reproduce that double exactly.
    add(",{\"bufferView\":%d,\"componentType\":5126,\"count\":%zu,\"type\":\"VEC3\","
        "\"min\":[%.17g,%.17g,%.17g],\"max\":[%.17g,%.17g,%.17g]}",
        view_pos, nv, mn[0], mn[1], mn[2], mx[0], mx[1], mx[2]);
    if (has_n)
        add(",{\"bufferView\":%d,\"componentType\":5126,\"count\":%zu,\"type\":\"VEC3\"}",
            view_nrm, nv);
    if (has_c)
        add(",{\"bufferView\":%d,\"componentType\":5126,\"count\":%zu,"
            "\"type\":\"VEC3\"}", view_col, nv);
    if (has_uv)
        add(",{\"bufferView\":%d,\"componentType\":5126,\"count\":%zu,\"type\":\"VEC2\"}",
            view_uv, nv);
    j += "],";

    // bufferViews + buffer
    j += "\"bufferViews\":[";
    for (size_t i = 0; i < views.size(); ++i) {
        add("%s{\"buffer\":0,\"byteOffset\":%zu,\"byteLength\":%zu",
            i ? "," : "", views[i].off, views[i].len);
        if (views[i].target) add(",\"target\":%d", views[i].target);
        j += "}";
    }
    j += "],";
    if (glb)
        add("\"buffers\":[{\"byteLength\":%zu}]}", bin.size());
    else
        add("\"buffers\":[{\"uri\":\"%s.bin\",\"byteLength\":%zu}]}", name.c_str(), bin.size());

    // ---- write ----
    if (glb) {
        while (j.size() % 4) j += ' ';
        uint32_t total = 12 + 8 + (uint32_t)j.size() + 8 + (uint32_t)bin.size();
        auto f = open_binary(base + ".glb");
        uint32_t hdr[3] = {0x46546C67u, 2u, total};
        f.write((const char*)hdr, 12);
        uint32_t jc[2] = {(uint32_t)j.size(), 0x4E4F534Au};
        f.write((const char*)jc, 8);
        f.write(j.data(), j.size());
        uint32_t bc[2] = {(uint32_t)bin.size(), 0x004E4942u};
        f.write((const char*)bc, 8);
        f.write((const char*)bin.data(), bin.size());
        f.flush();
        if (!f) fail("write failed for " + base + ".glb");
    } else {
        {
            std::ofstream f(base + ".gltf");
            if (!f) fail("cannot open " + base + ".gltf for writing");
            f << j;
            f.flush();
            if (!f) fail("write failed for " + base + ".gltf");
        }
        auto f = open_binary(base + ".bin");
        f.write((const char*)bin.data(), bin.size());
        f.flush();
        if (!f) fail("write failed for " + base + ".bin");
        if (has_uv) write_tex_file(mesh, spec, base + "." + spec.tex_ext());
    }
}

